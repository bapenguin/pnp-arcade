// Bytes 0 and 255 are blanks too; a typed space is byte 32.
const toByte = new Map<string, number>();
CP437.forEach((ch, i) => {
  if (i !== 0 && i !== 255 && !toByte.has(ch)) toByte.set(ch, i);
});

/** The CP437 byte for a character; '?' for anything the PC couldn't show. */
export function cp437Byte(ch: string): number {
  return toByte.get(ch) ?? 0x3f;
}
